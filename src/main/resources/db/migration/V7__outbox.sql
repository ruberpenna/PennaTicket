-- 6-2단계: Transactional Outbox
-- 예매 상태 변경과 "보낼 이벤트"를 같은 트랜잭션으로 저장한다. 커밋되면 둘 다 있고, 롤백되면 둘 다 없다.
-- 릴레이가 published_at이 비어 있는 행을 Kafka로 보내고 표시한다. 앱이 꺼져 있어도 이벤트는 DB에 남는다.
create table outbox_event
(
    id             bigint generated by default as identity primary key,
    aggregate_type varchar(50) not null, -- 예: Reservation
    aggregate_id   bigint      not null, -- 예: 예매 id (Kafka 메시지 키 → 같은 예매 이벤트는 순서 보장)
    event_type     varchar(50) not null, -- 예: Confirmed, Cancelled
    payload        text        not null, -- 이벤트 JSON
    created_at     timestamp   not null,
    published_at   timestamp             -- null = 아직 Kafka로 안 보냄
);

-- 릴레이는 "안 보낸 것"만 찾는다 → 그 행들만 인덱스에 담는 부분 인덱스
create index idx_outbox_unpublished on outbox_event (id) where published_at is null;

-- 소비자 쪽 중복 방지: 같은 이벤트가 두 번 와도 알림은 한 번만
alter table notification add column event_id bigint unique;
